export const OFFICER_HISTORY: Readonly<Record<string, OfficerTimeline>> = Object.fromEntries(
  Object.entries(HISTORICAL_OFFICER_HISTORY).map(([id, historical]) => {
    const game = SAN11_OFFICER_DATES[id];
    if (!game) throw new Error('Missing SAN11 reference: ' + id);
    const birthFromGame = historical.birthYear === null;
    const deathFromGame = historical.deathYear === null;
    const birthYear = historical.birthYear ?? game[0];
    const deathYear = historical.deathYear ?? game[1];
    const gameDebutBasis = GAME_DEBUT_BASIS[id];
    const selectedDebut = gameDebutBasis ? game[2] : historical.debutYear;
    const debutYear = Math.max(selectedDebut, birthYear + 15);
    const usesGame = birthFromGame || deathFromGame || gameDebutBasis !== undefined;
    return [
      id,
      {
        ...historical,
        birthYear,
        deathYear,
        birthKind: birthFromGame ? 'game-reference' : historical.birthKind,
        deathKind: deathFromGame ? 'game-reference' : historical.deathKind,
        debutYear,
        debutApproximate: gameDebutBasis !== undefined || historical.debutApproximate,
        debutKind: gameDebutBasis ? 'game-reference' : historical.debutKind,
        debutCityId: id === 'zhoutai' ? 'shouchun' : historical.debutCityId,
        sources: usesGame ? [...historical.sources, SAN11_REFERENCE_URL] : historical.sources,
        basis:
          (gameDebutBasis ?? historical.basis) +
          (debutYear > selectedDebut
            ? ' 参考登场年早于本作16岁虚岁下限，顺延至' + debutYear + '年。'
            : '') +
          (birthFromGame || deathFromGame
            ? ' 史料缺失的' +
              [birthFromGame ? '生年' : '', deathFromGame ? '卒年' : '']
                .filter(Boolean)
                .join('、') +
              '采用三国志11参考值，非史实断言。'
            : ''),
      } satisfies OfficerTimeline,
    ];
  }),
);
