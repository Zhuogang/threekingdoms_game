const s = (volume: number) =>
  `https://zh.wikisource.org/zh-hans/三國志/卷${String(volume).padStart(2, '0')}`;
const j = (volume: number) =>
  `https://zh.wikisource.org/zh-hans/晉書/卷${String(volume).padStart(3, '0')}`;

function history(
  birthYear: number | null,
  deathYear: number | null,
  debutYear: number,
  debutCityId: string,
  source: string,
  basis: string,
  overrides: Partial<
    Pick<OfficerTimeline, 'birthKind' | 'deathKind' | 'debutApproximate' | 'sources'>
  > = {},
): OfficerTimeline {
  return {
    birthYear,
    deathYear,
    birthKind: birthYear === null ? 'unknown' : 'inferred',
    deathKind: deathYear === null ? 'unknown' : 'recorded',
    debutYear,
    debutApproximate: true,
    debutKind: overrides.debutApproximate === false ? 'recorded' : 'design',
    debutCityId,
    sources: [source],
    basis,
    ...overrides,
  };
}

