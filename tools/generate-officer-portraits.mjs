import { readFile, writeFile, access } from 'node:fs/promises';
import { format, resolveConfig } from 'prettier';
import assert from 'node:assert/strict';

const manifest = JSON.parse(await readFile('public/assets/v03/portraits/manifest.json', 'utf8'));
const legacy = JSON.parse(await readFile('public/assets/portraits/credits.json', 'utf8'));
const paths = {};
for (const entry of manifest.entries) {
  // R4: keep the 53 existing early-scenario faces; revised renditions remain future variants.
  const files =
    entry.status === 'revised'
      ? legacy.entries.find((old) => old.id === entry.runtimeId)?.files
      : entry.files;
  assert(files, entry.runtimeId);
  const pair = [128, 256].map((size) => {
    const file = files.find((file) => file.width === size);
    assert(file, entry.runtimeId + ':' + size);
    return file.path ?? 'assets/portraits/' + file.file;
  });
  assert(!Object.hasOwn(paths, entry.runtimeId));
  paths[entry.runtimeId] = pair;
}
assert.equal(Object.keys(paths).length, 98);
paths.garrison = ['assets/portraits/garrison-small.webp', 'assets/portraits/garrison.webp'];
for (const pair of Object.values(paths))
  for (const path of pair) {
    assert(/^assets\/(?:v03\/)?portraits\/[a-z0-9_-]+\.webp$/.test(path), path);
    await access('public/' + path);
  }
const target = 'src/v03/content/officer-portraits.generated.ts';
const source =
  '// Generated by tools/generate-officer-portraits.mjs. No production prompts or provenance.\n' +
  '// The original 53 faces remain active in both early scenarios; 45 new faces use v03 assets.\n' +
  'export const OFFICER_PORTRAIT_PATHS: Readonly<Record<string, readonly [string, string]>> = ' +
  JSON.stringify(paths) +
  ';\n';
await writeFile(
  target,
  await format(source, { ...(await resolveConfig(target)), parser: 'typescript' }),
);
console.log('Generated 98 officer portrait mappings plus garrison; both rendition paths verified.');
