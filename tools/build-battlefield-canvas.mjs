import { chromium } from '@playwright/test';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile as writeFileNow } from 'node:fs/promises';
import { existsSync } from 'node:fs';

// Turns a chosen ImageGen attempt into the shipped battlefield canvas:
//   node tools/build-battlefield-canvas.mjs <battlefield-id> <attempt, e.g. v4>
// The attempt is re-encoded as lossy WebP through Chrome (no image libraries
// are installed here), stepping quality down until it fits the 1.5 MB budget.
// It keeps the attempt's 1536×1024 pixels: a plain resample to 3072×2048 adds
// bytes but no detail, and the renderer stretches it over the 48×32 board.
// Writes only changed files, retrying briefly: on Windows another process
// (indexer, antivirus, the dev server) sometimes holds a file for a moment.
async function writeFile(path, content) {
  const next = Buffer.from(content);
  const previous = await readFile(path).catch(() => null);
  if (previous?.equals(next)) return;
  for (let attempt = 0; ; attempt++) {
    try {
      return await writeFileNow(path, next);
    } catch (error) {
      if (attempt >= 5) throw error;
      await new Promise((resolve) => setTimeout(resolve, 200 * (attempt + 1)));
    }
  }
}

const [id, version] = process.argv.slice(2);
if (!id || !version)
  throw new Error('Usage: node tools/build-battlefield-canvas.mjs <id> <attempt>');
const MAX_BYTES = 1.5 * 1024 * 1024;
const source = `docs/v0.3/battlefield-art/${id}/attempts/${version}.webp`;
if (!existsSync(source)) throw new Error(`Missing ${source}`);
const output = `public/assets/v03/battlefields/${id}.webp`;
const record = 'docs/v0.3/assets/battlefield-canvases.json';
const registry = 'src/v03/rendering/battlefield-canvases.generated.ts';

const browser = await chromium.launch({ channel: process.env.CI ? undefined : 'chrome' });
let encoded;
try {
  const page = await browser.newPage();
  const sourceUrl = `data:image/webp;base64,${(await readFile(source)).toString('base64')}`;
  for (const quality of [0.9, 0.86, 0.82, 0.78, 0.74, 0.7]) {
    const result = await page.evaluate(
      async ({ sourceUrl, quality }) => {
        const image = new Image();
        image.src = sourceUrl;
        await image.decode();
        const canvas = document.createElement('canvas');
        canvas.width = image.naturalWidth;
        canvas.height = image.naturalHeight;
        canvas.getContext('2d').drawImage(image, 0, 0);
        const url = canvas.toDataURL('image/webp', quality);
        if (!url.startsWith('data:image/webp')) throw new Error('This browser cannot encode WebP.');
        return { base64: url.split(',')[1], width: canvas.width, height: canvas.height };
      },
      { sourceUrl, quality },
    );
    const bytes = Buffer.from(result.base64, 'base64');
    encoded = { ...result, bytes, quality };
    if (bytes.length <= MAX_BYTES) break;
  }
} finally {
  await browser.close();
}
if (encoded.bytes.length > MAX_BYTES)
  throw new Error(`${id}: ${encoded.bytes.length} bytes even at quality ${encoded.quality}.`);

await mkdir('public/assets/v03/battlefields', { recursive: true });
await writeFile(output, encoded.bytes);
const sha256 = createHash('sha256').update(encoded.bytes).digest('hex');
const sourceSha256 = createHash('sha256')
  .update(await readFile(source))
  .digest('hex');
const records = existsSync(record) ? JSON.parse(await readFile(record, 'utf8')) : {};
records[id] = {
  source,
  sourceSha256,
  path: output,
  width: encoded.width,
  height: encoded.height,
  quality: encoded.quality,
  bytes: encoded.bytes.length,
  sha256,
  status: 'integrated',
  encodedOn: new Date().toISOString().slice(0, 10),
};
const sorted = Object.fromEntries(Object.entries(records).sort(([a], [b]) => a.localeCompare(b)));
await writeFile(record, `${JSON.stringify(sorted, null, 2)}\n`);
await writeFile(
  registry,
  `// Generated by tools/build-battlefield-canvas.mjs; rerun it instead of editing this file.
/** Painted 48×32 battlefield canvases shipped under public/, keyed by battlefield id. */
export const V03_BATTLEFIELD_CANVASES: Readonly<
  Record<string, { path: string; width: number; height: number; sha256: string }>
> = {
${Object.entries(sorted)
  .map(
    ([key, entry]) =>
      `  '${key}': {\n    path: '${entry.path.replace(/^public\//, '')}',\n    width: ${entry.width},\n    height: ${entry.height},\n    sha256: '${entry.sha256}',\n  },`,
  )
  .join('\n')}
};
`,
);
console.log(
  JSON.stringify({ id, output, quality: encoded.quality, bytes: encoded.bytes.length, sha256 }),
);
